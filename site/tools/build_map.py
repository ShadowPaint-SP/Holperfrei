"""Builds site/js/map-data.js from an OpenStreetMap export of Dresden Äußere Neustadt.

Usage:
  curl -s --data-urlencode 'data=[out:json];(way["highway"~"^(primary|secondary|tertiary|residential|unclassified|living_street|pedestrian)$"](51.058,13.735,51.074,13.768);way["waterway"="river"](51.050,13.725,51.080,13.780););out geom;' \
    https://overpass-api.de/api/interpreter -o neustadt.json
  python3 site/tools/build_map.py neustadt.json > site/js/map-data.js

The damage points are invented sample data for the demo, not measurements.
"""
import heapq
import json
import math
import random
import sys

LAT0, LON0, LAT1, LON1 = 51.058, 13.735, 51.074, 13.768
W, H = 1300, 1000

# Truck route waypoints in normalised map coordinates (x, y), visited in order.
WAYPOINTS = [
    (0.43, 0.30), (0.47, 0.40), (0.49, 0.58), (0.56, 0.57), (0.63, 0.62),
    (0.62, 0.33), (0.72, 0.35), (0.78, 0.47), (0.56, 0.47), (0.42, 0.48),
    (0.54, 0.60), (0.54, 0.66),
]
MINOR = {"residential", "unclassified", "living_street"}


def proj(lat, lon):
    return ((lon - LON0) / (LON1 - LON0) * W, (LAT1 - lat) / (LAT1 - LAT0) * H)


def path_d(pts):
    return "M" + "L".join(f"{x:.0f} {y:.0f}" for x, y in pts)


def main():
    data = json.load(open(sys.argv[1]))
    major, minor, river = [], [], []
    graph, coord, street_of = {}, {}, {}
    for e in data["elements"]:
        tags = e.get("tags", {})
        pts = [proj(p["lat"], p["lon"]) for p in e["geometry"]]
        if tags.get("waterway") == "river":
            river.append(pts)
            continue
        (minor if tags["highway"] in MINOR else major).append(pts)
        if tags["highway"] == "pedestrian":
            continue
        name = tags.get("name", "")
        for nid, pt in zip(e["nodes"], pts):
            coord[nid] = pt
        for a, b in zip(e["nodes"], e["nodes"][1:]):
            dist = math.dist(coord[a], coord[b])
            graph.setdefault(a, []).append((b, dist))
            graph.setdefault(b, []).append((a, dist))
            street_of[(a, b)] = street_of[(b, a)] = name

    def nearest(x, y):
        return min(graph, key=lambda n: math.dist(coord[n], (x * W, y * H)))

    def shortest(src, dst):
        prev, best, heap = {}, {src: 0}, [(0, src)]
        while heap:
            d, n = heapq.heappop(heap)
            if n == dst:
                break
            if d > best[n]:
                continue
            for m, w in graph[n]:
                if d + w < best.get(m, 1e18):
                    best[m], prev[m] = d + w, n
                    heapq.heappush(heap, (d + w, m))
        out = [dst]
        while out[-1] != src:
            out.append(prev[out[-1]])
        return out[::-1]

    nodes = [nearest(x, y) for x, y in WAYPOINTS]
    route = [nodes[0]]
    for a, b in zip(nodes, nodes[1:]):
        route += shortest(a, b)[1:]
    route_pts = [coord[n] for n in route]

    # Sample damage along the route, spaced evenly, with a fixed seed.
    rnd = random.Random(47)
    seg_len = [math.dist(p, q) for p, q in zip(route_pts, route_pts[1:])]
    total = sum(seg_len)
    damages = []
    kinds = [
        ("Pothole", 3), ("Crack network", 2), ("Pothole", 3), ("Long crack", 1),
        ("Edge break", 2), ("Long crack", 1), ("Pothole", 3), ("Crack network", 2),
        ("Long crack", 1), ("Sunken patch", 2), ("Pothole", 3), ("Long crack", 1),
    ]
    for i, (kind, sev) in enumerate(kinds):
        target = total * (i + 0.6) / (len(kinds) + 0.4)
        acc = 0
        for j, s in enumerate(seg_len):
            if acc + s >= target:
                t = (target - acc) / s
                (x0, y0), (x1, y1) = route_pts[j], route_pts[j + 1]
                street = street_of.get((route[j], route[j + 1]), "")
                break
            acc += s
        damages.append({
            "x": round(x0 + (x1 - x0) * t), "y": round(y0 + (y1 - y0) * t),
            "at": round(target / total, 3), "kind": kind, "sev": sev, "street": street,
        })

    # Faint background damage found by other trucks, on minor streets only.
    minor_nodes = [n for n in graph if any(street_of.get((n, m)) for m, _ in graph[n])]
    rnd.shuffle(minor_nodes)
    others = [{"x": round(coord[n][0]), "y": round(coord[n][1]), "sev": rnd.choice([1, 1, 1, 2, 2, 3])}
              for n in minor_nodes[:46]]

    out = {
        "w": W, "h": H,
        "major": " ".join(path_d(p) for p in major),
        "minor": " ".join(path_d(p) for p in minor),
        "river": " ".join(path_d(p) for p in river),
        "route": path_d(route_pts),
        "routeKm": round(total * (LAT1 - LAT0) * 111.2 / H, 1),
        "damages": damages,
        "others": others,
    }
    print("// Generated by site/tools/build_map.py from OpenStreetMap data (ODbL). Damage points are sample data.")
    print("window.HOLPERFREI_MAP = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";")


main()
